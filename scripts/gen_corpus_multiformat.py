# ----------------------------------------------------------------------
# 断言取值
# ----------------------------------------------------------------------

# 「不涉及金额」「不限名额」这类值出现在正文里，但拿它当断言等于没断言。
NO_INFO = {"", "无", "不涉及金额", "不限名额", "按需申请", "不收费", "无需报名",
           "不设要求", "不设面试", "不涉及出境", "按实际就业人数"}

# 断言长度上限。见 render() 的说明。
MAX_ANCHOR = 24

_DATE_RE = re.compile(r"\d{4}年\d{1,2}月\d{1,2}日|\d{4}年\d{1,2}月|\d{1,2}月\d{1,2}日")


def first_date(text: str) -> str | None:
    """从长句里挑第一个日期当断言锚点。

    `schedule` 这类字段往往是一整段话，整段做断言既长又容易被标点差异弄挂。
    抽一个具体日期出来，短、稳定、还能真正验证「模型有没有读到那一条」。
    """
    m = _DATE_RE.search(text or "")
    return m.group(0) if m else None


def anchors(*values: str | None) -> list[str]:
    out: list[str] = []
    for v in values:
        if not v or v in NO_INFO:
            continue
        if v not in out:
            out.append(v)
    return out


# ----------------------------------------------------------------------
# 落盘：四种格式
# ----------------------------------------------------------------------


def safe_name(text: str) -> str:
    """文件名不能带路径分隔符和 Windows 保留字符。"""
    return re.sub(r'[\\/:*?"<>|\r\n]', "", text).strip()[:60]


def front_matter(p: dict) -> str:
    return (
        "---\n"
        f"title: {p['title']}\n"
        f"doc_no: {p['doc_no'].format(p['seq'])}\n"
        f"department: {p['department']}\n"
        f"doc_type: {p['doc_type']}\n"
        f"college: {p['college']}\n"
        f"publish_date: {p['date']}\n"
        f"url: https://www.example.edu.cn/notice/{p['date'].replace('-', '')}.html\n"
        "---\n\n"
    )


def sidecar_yaml(p: dict) -> str:
    """PDF / docx 是二进制，元数据放同名侧车。

    yaml 里含中文冒号、书名号的值一律加引号，否则 safe_load 会把
    「关于做好…：…」里的冒号当成键值分隔符，整份元数据解析失败。
    """
    def q(v: str) -> str:
        return '"' + str(v).replace('\\', '\\\\').replace('"', '\\"') + '"'

    return (
        f"title: {q(p['title'])}\n"
        f"doc_no: {q(p['doc_no'].format(p['seq']))}\n"
        f"department: {q(p['department'])}\n"
        f"doc_type: {q(p['doc_type'])}\n"
        f"college: {q(p['college'])}\n"
        f"publish_date: {q(p['date'])}\n"
        f"url: {q('https://www.example.edu.cn/notice/' + p['date'].replace('-', '') + '.html')}\n"
    )


def write_pdf(path: Path, body: str) -> None:
    from fpdf import FPDF

    pdf = FPDF()
    pdf.set_margins(15, 15, 15)
    pdf.set_auto_page_break(True, margin=15)
    pdf.add_font("hei", "", FONT)
    pdf.set_font("hei", size=11)
    pdf.add_page()
    for line in body.split("\n"):
        # width 必须显式给（传 0 用剩余宽度在 fpdf2 2.8 会抛
        # "Not enough horizontal space"）；空行也要占位，否则段落会挤在一起
        pdf.multi_cell(180, 7, line if line.strip() else " ")
    pdf.output(str(path))


def write_docx(path: Path, body: str) -> None:
    import docx

    document = docx.Document()
    for line in body.split("\n"):
        document.add_paragraph(line)
    document.save(str(path))


def render(p: dict) -> tuple[str, list[str]]:
    fn = TEMPLATES[p["tpl"]]
    body, facts = fn(p)
    # 超过二十来个字的断言不适合做字符匹配：模型答对意思但换了个语序，
    # 就会判成失败，这类伪失败比真失败更浪费时间。
    cleaned = [str(f) for f in facts
               if f is not None and str(f) not in NO_INFO and len(str(f)) <= MAX_ANCHOR]
    # 一个断言都没有时才补日期。以前写成「少于 2 个就补」，结果给 award 类
    # 硬塞了一个截止日期 —— 而那条用例只问「要交什么材料」，模型不提日期
    # 才是对的，补上去等于凭空制造一次失败。
    if not cleaned:
        extra = first_date(body)
        if extra:
            cleaned.append(extra)
    return body.strip(), cleaned


def emit(specs: list[dict], out_dir: Path, start_no: int, dry: bool) -> list[dict]:
    docs: list[dict] = []
    for i, p in enumerate(specs):
        no = start_no + i
        p["seq"] = no
        fmt = FORMATS[i % len(FORMATS)]
        body, facts = render(p)
        fname = f"{no:02d}_{p['doc_type']}_{p['date']}_{safe_name(p['title'])}.{fmt}"
        path = out_dir / fname

        if not dry:
            if fmt in ("md", "txt"):
                path.write_text(front_matter(p) + body + "\n", encoding="utf-8")
            else:
                if fmt == "pdf":
                    write_pdf(path, body)
                else:
                    write_docx(path, body)
                # 侧车：`xxx.pdf.meta.yaml`
                (out_dir / (fname + ".meta.yaml")).write_text(
                    sidecar_yaml(p), encoding="utf-8")

        docs.append({**p, "fmt": fmt, "file": fname, "body": body,
                     "facts": facts, "chars": len(body)})
    return docs


