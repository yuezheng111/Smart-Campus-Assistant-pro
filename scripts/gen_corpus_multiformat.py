# 从文档派生 document 类用例
# ----------------------------------------------------------------------

# 每类文档问什么。
#
# 一条硬规则：**document 类只能问「文件里才有、库里查不到」的内容**。
# 第一版写的是「什么时候考试？报名费多少？」—— 可这两项在 MySQL 的
# `exam` 表里躺着，模型判成 structured 完全正确，是我标错了。258 条跑下来
# 路由准确率 81.4%，其中 26 条错误全来自这一处标注错误。
# 现在改成问条件、材料、流程、准考证这类只在正文里的信息。
QUESTION = {
    "award": "申请{year}年{name}要交哪些材料？",
    "exam": "{name}的准考证什么时候能打印？",
    "contest": "{name}的赛程是怎么安排的？省赛在什么时候？",
    "service": "{item}要怎么办？在哪里办？",
    "activity": "{name}有哪些内容？在哪里办？",
    "academic": "{term}{item}对学生有什么具体要求？",
    "regulation": "《{title}》从什么时候开始施行？由哪个部门负责解释？",
    "employment": "{name}对参会的学生有什么要求？",
    "exchange": "申请{name}需要什么条件？有多少名额？",
}


def make_document_cases(docs: list[dict], start: int = 1) -> list[dict]:
    cases: list[dict] = []
    for i, d in enumerate(docs):
        q = QUESTION[d["tpl"]].format(**d)
        cases.append({
            "id": f"B{start + i:03d}",
            "category": "document",
            "question": q,
            "expected_route": "document",
            "expected_titles": [d["title"]],
            "must_contain": d["facts"],
            "_fmt": d["fmt"],
            "_doc_type": d["doc_type"],
            "_tpl": d["tpl"],
        })
    return cases


