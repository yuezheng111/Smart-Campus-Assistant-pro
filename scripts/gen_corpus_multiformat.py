def tpl_award(p: dict) -> tuple[str, list[str]]:
    kind = p.get("kind", "奖励")
    # 金额与名额的句式在各类项目里差别太大：「每人每年 8000 元」「120 个岗位」
    # 「不限名额」硬套同一个模板会写出病句，所以允许 SPEC 给整句覆盖。
    amount_line = p.get("amount_line") or (
        f"{p['name']}{kind}标准为每人每年 {p['amount']}，一次性发放。"
    )
    quota_line = p.get("quota_line") or (
        f"{p['year']} 年上级下达我校名额 {p['quota']}，按各学院{p['who']}在校生人数比例分配，具体名额见附件 1。"
    )
    conflict_line = (
        "同一学年内，可同时申请其他奖助项目。"
        if p.get("conflict") in (None, "", "无")
        else f"同一学年内，不得同时获得{p['conflict']}。"
    )
    body = f"""各学院、各位同学：

根据《{p['policy']}》及上级有关文件精神，现将我校 {p['year']} 年{p['name']}评选工作有关事项通知如下。

一、{kind}标准与名额
{amount_line}{quota_line}

二、申请条件
1. 具有中华人民共和国国籍，拥护中国共产党的领导，遵守宪法和法律，遵守学校规章制度；
2. 诚实守信，道德品质优良，{p['cond']}；
3. {p['grade']}；
4. {conflict_line}

三、评审程序
1. 学生申请（{p['start']}至{p['end']}）：符合条件的学生向所在学院提交申请表及证明材料，逾期不再受理；
2. 学院初评（{p['review']}）：各学院成立评审小组，按分配名额 1:1.2 确定推荐名单，在学院范围内公示 3 个工作日；
3. 学校审定：学生工作处汇总各学院材料，报学校评审领导小组审定，审定结果在全校范围内公示 5 个工作日；
4. 资金发放：公示无异议后，由财务处统一发放至学生本人银行账户，不发放现金。

四、材料要求
《{p['form']}》一式两份，须加盖学院公章；加盖教务处公章的成绩单原件；
{p['material']}。材料不齐或弄虚作假的，取消本年度及下一年度申请资格。

五、联系方式
联系人：{p['contact']}　联系电话：{p['phone']}　办公地点：{p['office']}

{p['department']}
{p['date']}
"""
