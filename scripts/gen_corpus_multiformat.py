def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--start", type=int, default=0, help="起始编号，默认接着 data/raw 现有最大编号")
    ap.add_argument("--cases", default=str(CASES_OUT))
    args = ap.parse_args()

    start_no = args.start
    if not start_no:
        mx = 0
        for f in RAW_DIR.glob("*"):
            m = re.match(r"^(\d+)_", f.name)
            if m:
                mx = max(mx, int(m.group(1)))
        start_no = mx + 1

    docs = emit(SPECS, RAW_DIR, start_no, args.dry_run)
    cases = make_document_cases(docs)

    print(f"{'[dry-run] ' if args.dry_run else ''}生成 {len(docs)} 份文档 → {RAW_DIR}")
    by_fmt: dict[str, int] = {}
    by_type: dict[str, int] = {}
    for d in docs:
        by_fmt[d["fmt"]] = by_fmt.get(d["fmt"], 0) + 1
        by_type[d["doc_type"]] = by_type.get(d["doc_type"], 0) + 1
    print("  格式分布：", dict(sorted(by_fmt.items())))
    print("  类型分布：", dict(sorted(by_type.items())))
    print(f"  正文合计 {sum(d['chars'] for d in docs)} 字，平均 {sum(d['chars'] for d in docs) // len(docs)} 字/篇")
    print(f"  用例 {len(cases)} 条 → {args.cases}")

    if not args.dry_run:
        with open(args.cases, "w", encoding="utf-8") as f:
            for c in cases:
                f.write(json.dumps(c, ensure_ascii=False) + "\n")

    # 断言自检：must_contain 必须真的在正文里，否则就是伪失败
    bad = 0
    for d, c in zip(docs, cases):
        for token in c["must_contain"]:
            if token not in d["body"]:
                bad += 1
                print(f"  [断言不成立] {d['title'][:24]} → {token!r}", file=sys.stderr)
    print(f"  断言自检：{sum(len(c['must_contain']) for c in cases)} 条断言，{bad} 条不成立")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())


