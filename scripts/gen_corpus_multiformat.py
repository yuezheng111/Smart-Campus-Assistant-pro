def spec(tpl: str, title: str, doc_type: str, department: str, college: str,
         date: str, **kw) -> dict:
    """把一条 SPEC 补全成渲染所需的完整参数。"""
    p = {**DEFAULTS[tpl], **kw}
    p.update(tpl=tpl, title=title, doc_type=doc_type,
             department=department, college=college, date=date,
             year=int(date[:4]))
    if not p.get("doc_no"):
        p["doc_no"] = DEFAULT_DOC_NO.get(department, "校发") + f"〔{p['year']}〕{{}}号"
    return p


