"""批量生成多格式语料（md / txt / pdf / docx）及其配套评测用例。

为什么要同源生成
----------------
用例里的 `must_contain` 必须是文档里真实出现的字符串。如果文档和用例分开
人工维护，迟早出现「断言写的是 8000 元、文档里是 8000元（带空格）」这类
伪失败，查起来极费时间。这里让一份 SPEC 同时产出正文和断言，从结构上
排除这种错位。

为什么值得做多格式
------------------
`app/rag/loader.py` 支持 .md/.txt/.pdf/.docx 四条解析路径，但此前只有 .md
被真正跑过 —— 另外三条是「写了但没验证」。真实学校里 PDF 红头文件才是主流，
只测 md 等于没测最关键的路径。PDF / docx 是二进制，塞不进 front-matter，
元数据走同名侧车 `<文件名>.meta.yaml`。

用法
----
    python scripts/gen_corpus_multiformat.py            # 生成语料 + 用例
    python scripts/gen_corpus_multiformat.py --dry-run  # 只看统计
"""

